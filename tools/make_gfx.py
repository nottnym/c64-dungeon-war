charset = bytearray(2048)
names = {}


def hires(code, name, rows):
    assert len(rows) == 8 and all(len(r) == 8 for r in rows), name
    for y, r in enumerate(rows):
        charset[code * 8 + y] = sum(1 << (7 - x) for x, ch in enumerate(r) if ch == '#')
    names[code] = name


def multi(code, name, rows):
    assert len(rows) == 8 and all(len(r) == 4 for r in rows), (name, rows)
    for y, r in enumerate(rows):
        v = 0
        for ch in r:
            v = (v << 2) | ('.123'.index(ch))
        charset[code * 8 + y] = v
    names[code] = name


