# --- sprity ----------------------------------------------------------------------------------------
sprites = []
spr_names = []


def sprite(name, rows):
    assert len(rows) == 21 and all(len(r) == 12 for r in rows), (name, [len(r) for r in rows])
    data = bytearray(64)
    for y, r in enumerate(rows):
        bits = 0
        for ch in r:
            bits = (bits << 2) | '.123'.index(ch)
        data[y * 3:y * 3 + 3] = bits.to_bytes(3, 'big')
    sprites.append(bytes(data))
    spr_names.append(name)


def mirror(rows):
    return [r[::-1] for r in rows]


def flip(rows):
    return rows[::-1]


def rot(rows):
    """otočenie o 90° doprava (približné – sprite 12 × 21 dvojpixelov nie je štvorcový): stred 12 × 12 sa otočí."""
    sq = [r for r in rows[4:16]]
    out = ["".join(sq[11 - x][y] for x in range(12)) for y in range(12)]
    pad = "............"
    return [pad] * 4 + out + [pad] * 5


