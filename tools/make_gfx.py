# Rohy: kde sa v znaku stretnú dve steny, kreslí sa „kameň“ – a stĺpik v každom rohu bunky (aj bez stien) dáva
# kód 80 + roh (0 ĽH, 1 PH, 2 ĽD, 3 PD) pre prípad, že v rohu nie je žiadna stena tejto bunky.
STONE_H = ["3133", "1313"]           # vodorovná stena (2 riadky) – kamene so škárami ($D022)
def wall_char(mask):
    rows = [list("....") for _ in range(8)]
    if mask & 1:   # hore
        rows[0] = list(STONE_H[0]); rows[1] = list(STONE_H[1])
    if mask & 2:   # dole
        rows[6] = list(STONE_H[0]); rows[7] = list(STONE_H[1])
    for y in range(8):
        if mask & 4:
            rows[y][0] = '3' if y % 3 else '1'
        if mask & 8:
            rows[y][3] = '3' if (y + 1) % 3 else '1'
    return ["".join(r) for r in rows]


